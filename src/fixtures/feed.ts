export function getFeedByKind(kind: FeedItem["kind"]): FeedItem[] {
  return FEED_ITEMS.filter((f) => f.kind === kind).sort(
    (a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime(),
  );
}

export function getFeedByAssignee(assigneeId: string): FeedItem[] {
  return FEED_ITEMS.filter((f) => f.assigneeId === assigneeId);
}

export function getFeedByProject(projectId: string): FeedItem[] {
  return FEED_ITEMS.filter((f) => f.projectId === projectId);
}
